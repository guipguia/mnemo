package store

import (
	"context"
	"database/sql"
	"strconv"
	"strings"
)

// Queries are written once, with ? placeholders and SQL that SQLite and PostgreSQL both
// accept. db and tx rewrite the placeholders to $1, $2, ... for PostgreSQL; the few real
// differences are methods on db.

type db struct {
	*sql.DB
	pg bool
}

type tx struct {
	*sql.Tx
	pg bool
}

func (d db) ExecContext(ctx context.Context, q string, args ...any) (sql.Result, error) {
	return d.DB.ExecContext(ctx, rebind(d.pg, q), args...)
}

func (d db) QueryContext(ctx context.Context, q string, args ...any) (*sql.Rows, error) {
	return d.DB.QueryContext(ctx, rebind(d.pg, q), args...)
}

func (d db) QueryRowContext(ctx context.Context, q string, args ...any) *sql.Row {
	return d.DB.QueryRowContext(ctx, rebind(d.pg, q), args...)
}

// BeginTx starts a transaction. On PostgreSQL it first takes a database-wide write lock, held
// until commit, so several hubs on one database write one at a time, as one hub does: no two
// can both read an object's latest version and append the next, and change IDs commit in
// order, so a webhook cursor never passes an ID that commits later.
// ponytail: one global write lock; per-cluster locks and gap-tolerant cursors if write
// throughput across hubs ever matters.
func (d db) BeginTx(ctx context.Context, opts *sql.TxOptions) (*tx, error) {
	t, err := d.DB.BeginTx(ctx, opts)
	if err != nil {
		return nil, err
	}
	if d.pg {
		if _, err := t.ExecContext(ctx, "SELECT pg_advisory_xact_lock($1)", writeLock); err != nil {
			t.Rollback()
			return nil, err
		}
	}
	return &tx{t, d.pg}, nil
}

// Advisory lock keys, arbitrary but fixed: every hub must agree on them.
const (
	writeLock  int64 = 0x6d6e656d6f01 // "mnemo" 1
	leaderLock int64 = 0x6d6e656d6f02
)

func (t *tx) ExecContext(ctx context.Context, q string, args ...any) (sql.Result, error) {
	return t.Tx.ExecContext(ctx, rebind(t.pg, q), args...)
}

func (t *tx) QueryContext(ctx context.Context, q string, args ...any) (*sql.Rows, error) {
	return t.Tx.QueryContext(ctx, rebind(t.pg, q), args...)
}

func (t *tx) QueryRowContext(ctx context.Context, q string, args ...any) *sql.Row {
	return t.Tx.QueryRowContext(ctx, rebind(t.pg, q), args...)
}

// rebind numbers the ? placeholders for PostgreSQL. No query has a literal "?".
func rebind(pg bool, q string) string {
	if !pg || !strings.Contains(q, "?") {
		return q
	}
	var b strings.Builder
	n := 0
	for _, r := range q {
		if r == '?' {
			n++
			b.WriteString("$" + strconv.Itoa(n))
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// greatest is the two-argument maximum: max() in SQLite, greatest() in PostgreSQL.
func (d db) greatest() string {
	if d.pg {
		return "greatest"
	}
	return "max"
}

